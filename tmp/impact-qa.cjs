const path=require('node:path'),os=require('node:os'),fs=require('node:fs');
const {pathToFileURL}=require('node:url');
const {chromium}=require('/Users/22p/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root=path.resolve(__dirname,'..');
const cache=path.join(os.homedir(),'Library/Caches/ms-playwright');
const shell=fs.readdirSync(cache).filter(x=>/^chromium_headless_shell-\d+$/.test(x)).sort((a,b)=>Number(b.split('-')[1])-Number(a.split('-')[1])).map(x=>path.join(cache,x,'chrome-headless-shell-mac-arm64/chrome-headless-shell')).find(x=>fs.existsSync(x));
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:shell});
  const page=await browser.newPage({viewport:{width:1200,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(root,'sim_interactive_demo.html')).href);
  await page.waitForFunction(()=>window.SIMDemo?.latest?.result.ok);
  await page.evaluate(()=>{document.getElementById('tab2Btn').click();document.querySelectorAll('#tab2Content details').forEach(d=>d.open=true);});
  const impact=()=>page.evaluate(()=>document.getElementById('wAerrImpact').textContent);
  console.log('default:',await impact());
  await page.evaluate(()=>{const el=document.getElementById('wAangle');el.value=3;el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.waitForTimeout(250);
  console.log('angle3 both:',await impact());
  await page.evaluate(()=>document.getElementById('wAscopeRecon').click());
  await page.waitForTimeout(250);
  console.log('angle3 recon:',await impact());
  console.log('hidden value:',await page.evaluate(()=>document.getElementById('wAerrScope').value));
  await page.evaluate(()=>{const el=document.getElementById('wAphase');el.value=2;el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.waitForTimeout(250);
  console.log('+phase2:',await impact());
  await page.locator('details.sim-error-card:has(#wAerrImpact)').screenshot({path:path.join(__dirname,'impact-qa.png')});
  console.log('errors:',errors);
  await browser.close();
})();
